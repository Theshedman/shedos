// Prebuild hook: emit src/generated/changelog.ts from git history.
//
// Mirrors build-iso.yml's release-notes grouping: for each stable tag
// (vYYYY.MM.DD, no -rcN), collect the commits back to the PREVIOUS
// stable tag and bucket them by conventional-commit type. rc tags are
// skipped — the stable entry rolls their contents up, same as the
// GitHub Release pages. Runs in deploy-site.yml's fetch-depth:0
// checkout, so tags + full history are present; on a shallow local
// clone it degrades to an empty list and the page renders a notice.

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const outDir = path.join(here, "..", "src", "generated");
const outFile = path.join(outDir, "changelog.ts");

const MAX_RELEASES = 8;

const BUCKETS = [
    ["feat", "New"],
    ["fix", "Fixed"],
    ["perf", "Performance"],
    ["refactor", "Internals"],
    ["docs", "Docs"],
    ["test", "Testing"],
    ["chore", "Chores"],
];

function git(cmd) {
    try {
        return execSync(`git ${cmd}`, {
            cwd: path.join(here, "..", ".."),
            encoding: "utf8",
            stdio: ["ignore", "pipe", "ignore"],
        }).trim();
    } catch {
        return "";
    }
}

const stableTags = git("tag --list 'v*' --sort=-creatordate")
    .split("\n")
    .filter((t) => /^v\d{4}\.\d{2}\.\d{2}$/.test(t));

const releases = [];
for (let i = 0; i < Math.min(stableTags.length, MAX_RELEASES); i++) {
    const tag = stableTags[i];
    const prev = stableTags[i + 1];
    const range = prev ? `${prev}..${tag}` : tag;
    const date = git(`log -1 --format=%cs ${tag}`);
    const subjects = git(`log --no-merges --format=%s ${range}`)
        .split("\n")
        .filter(Boolean)
        // The bot's bump commits are release plumbing, not news.
        .filter((s) => !s.startsWith("chore(release):"));

    const groups = [];
    for (const [type, label] of BUCKETS) {
        const re = new RegExp(`^${type}(\\([^)]*\\))?!?:\\s*`);
        const items = subjects
            .filter((s) => re.test(s))
            .map((s) => {
                const scope = s.match(/^[a-z]+\(([^)]*)\)/)?.[1] ?? null;
                return { scope, text: s.replace(re, "") };
            });
        if (items.length) groups.push({ label, items });
    }
    releases.push({ version: tag.slice(1), date, groups });
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
    outFile,
    `// Generated by scripts/gen-changelog.mjs — do not edit.
export interface ChangeItem { scope: string | null; text: string }
export interface ChangeGroup { label: string; items: ChangeItem[] }
export interface Release { version: string; date: string; groups: ChangeGroup[] }
export const RELEASES: Release[] = ${JSON.stringify(releases, null, 2)};
`,
);
console.log(`changelog: ${releases.length} stable release(s) emitted`);
