// Prebuild hook: find the newest published stable ISO AND the newest
// published RC on repo.shedos.org, and emit both so the download page
// can show "Stable" and "Testing" side-by-side.
//
// A stable version matches YYYY.MM.DD. An RC matches YYYY.MM.DD-rcN.
// The RC is only advertised when it's strictly newer (by date) than
// the latest published stable — otherwise there's nothing fresh to
// test and we hide it.
//
// If the bucket is unreachable entirely (offline build), we emit
// nulls and the page degrades to a plain "source on GitHub" state.

import { execSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const siteRoot = path.resolve(here, "..");
const repoRoot = path.resolve(siteRoot, "..");

const versionFile = fs.readFileSync(path.join(repoRoot, "VERSION"), "utf8").trim();

const STABLE_RE = /^\d{4}\.\d{2}\.\d{2}$/;
const RC_RE = /^\d{4}\.\d{2}\.\d{2}-rc\d+$/;

function gitTags() {
    try {
        return execSync("git tag --sort=-v:refname", {
            cwd: repoRoot,
            encoding: "utf8",
        })
            .split("\n")
            .map((t) => t.trim().replace(/^v/, ""))
            .filter(Boolean);
    } catch {
        return [];
    }
}

function dedup(list) {
    const seen = new Set();
    const out = [];
    for (const v of list) {
        if (v && !seen.has(v)) {
            seen.add(v);
            out.push(v);
        }
    }
    return out;
}

function dateOf(version) {
    return version.slice(0, 10);
}

async function probe(version) {
    const iso = `shedos-${version}-x86_64.iso`;
    const isoUrl = `https://repo.shedos.org/iso/${iso}`;
    const sha256Url = `${isoUrl}.sha256`;
    try {
        const res = await fetch(sha256Url, { signal: AbortSignal.timeout(10_000) });
        if (!res.ok) return null;
        const body = (await res.text()).trim();
        const first = body.split(/\s+/)[0];
        if (!/^[a-fA-F0-9]{64}$/.test(first)) return null;
        return {
            version,
            iso,
            isoUrl,
            sha256Url,
            sha256: first.toLowerCase(),
        };
    } catch {
        return null;
    }
}

async function firstResolved(candidates) {
    for (const v of candidates) {
        const r = await probe(v);
        if (r) return r;
    }
    return null;
}

const tags = gitTags();

const stableCandidates = dedup([
    ...(STABLE_RE.test(versionFile) ? [versionFile] : []),
    ...tags.filter((t) => STABLE_RE.test(t)),
]);

const rcCandidates = dedup([
    ...(RC_RE.test(versionFile) ? [versionFile] : []),
    ...tags.filter((t) => RC_RE.test(t)),
]);

const stable = await firstResolved(stableCandidates);
let rc = await firstResolved(rcCandidates);

if (stable && rc && dateOf(rc.version) <= dateOf(stable.version)) {
    rc = null;
}

const gen = path.join(siteRoot, "src", "generated");
fs.mkdirSync(gen, { recursive: true });

function emit(prefix, r) {
    if (!r) {
        return (
            `export const ${prefix}_VERSION: string | null = null;\n` +
            `export const ${prefix}_ISO_NAME: string | null = null;\n` +
            `export const ${prefix}_ISO_URL: string | null = null;\n` +
            `export const ${prefix}_SHA256: string | null = null;\n` +
            `export const ${prefix}_SHA256_URL: string | null = null;\n`
        );
    }
    return (
        `export const ${prefix}_VERSION = ${JSON.stringify(r.version)};\n` +
        `export const ${prefix}_ISO_NAME = ${JSON.stringify(r.iso)};\n` +
        `export const ${prefix}_ISO_URL = ${JSON.stringify(r.isoUrl)};\n` +
        `export const ${prefix}_SHA256 = ${JSON.stringify(r.sha256)};\n` +
        `export const ${prefix}_SHA256_URL = ${JSON.stringify(r.sha256Url)};\n`
    );
}

const out =
    `// AUTO-GENERATED by site/scripts/sync-version.mjs — do not edit.\n` +
    `// Regenerated on every \`npm run build\` / \`npm run dev\` via the prebuild hook.\n` +
    emit("STABLE", stable) +
    emit("RC", rc);

fs.writeFileSync(path.join(gen, "version.ts"), out);

console.log(
    `[sync-version] stable=${stable?.version ?? "none"} rc=${rc?.version ?? "none"}`,
);
