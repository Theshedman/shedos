"""ShedOS theme reconciler.

Reads /etc/shedos/system.toml's [theme] section + the named palette TOML
under /etc/shedos/themes/palettes/, and renders nine canonical outputs
into /etc/shedos/themes/current/:

  palette.lua       Lua table  (dofile'd by ~/.config/hypr/hyprland.lua;
                    drives border + shadow colors)
  palette.conf      Hyprland $vars  (legacy hyprlang form; kept for user
                    configs that still source it)
  palette.css       CSS @define-color  (imported by waybar/walker styles)
  kitty-colors.conf Terminal colors  (included by ~/.config/kitty/kitty.conf)
  mako-colors.conf  Notification colors  (included by ~/.config/mako/config)
  fzf.zsh           FZF_DEFAULT_OPTS export  (sourced by the skel .zshrc)
  greeter.toml      Concrete values for shedos-greeter / prompt-ui Theme
  gsettings.sh      `gsettings set …` script (executed at Hyprland startup)
  wallpaper.png     Symlink → [theme].wallpaper

Plus one sentinel:

  .applied-at     Unix timestamp of the most recent successful swap;
                  inotify watchers (e.g. shedos-prompt-ui) trigger off
                  this file (or off MOVED_TO on `current` from the
                  parent dir) for a single stable signal per apply.

Re-rendered any time `shedman apply`, `shedman theme apply`, or this
module is invoked directly. The output directory is rewritten via a
`current.tmp/ → current/` rename so a half-render never serves; a
validation pass before the rename refuses to swap when any output is
malformed (caller's `current/` keeps the previous good theme).
"""

import argparse
import re
import shutil
import subprocess
import sys
import time
from pathlib import Path

import tomlkit
import tomlkit.exceptions as tomlkit_exc


SCHEMA_VERSION = 1

DEFAULT_PALETTE = "catppuccin-mocha-blue"
DEFAULT_WALLPAPER = "/usr/share/shedos/wallpapers/dusk.png"
DEFAULT_FONT_UI = "Inter 11"
DEFAULT_FONT_MONO = "JetBrainsMono Nerd Font"

# Strength of the gaussian blur applied to user-set wallpapers that
# lack a shipped -blurred companion. Tuned to match the look of
# dusk-blurred.png and the other shipped variants.
WALLPAPER_BLUR_KERNEL = "0x30"

HEX_COLOR_RE = re.compile(r"^#[0-9a-fA-F]{6}$")


class ThemeRenderError(Exception):
    pass


def _resolve_theme_inputs(system_doc, etc_root):
    theme = (system_doc.get("theme") if isinstance(system_doc, dict) else None) or {}
    wallpaper = theme.get("wallpaper", DEFAULT_WALLPAPER)
    palette_name = theme.get("palette", DEFAULT_PALETTE)
    font_ui = theme.get("font_ui", DEFAULT_FONT_UI)
    font_mono = theme.get("font_mono", DEFAULT_FONT_MONO)

    palette_path = etc_root / "shedos" / "themes" / "palettes" / f"{palette_name}.toml"
    if not palette_path.is_file():
        raise ThemeRenderError(
            f"palette {palette_name!r} not found at {palette_path}"
        )
    palette = tomlkit.parse(palette_path.read_text())
    colors = {k: str(v) for k, v in dict(palette.get("colors", {})).items()}
    if not colors:
        raise ThemeRenderError(f"palette {palette_name!r} has no [colors] table")
    for name, value in colors.items():
        if not HEX_COLOR_RE.match(value):
            raise ThemeRenderError(
                f"palette {palette_name!r} color {name!r}={value!r} is not #rrggbb"
            )
    accent = palette.get("accent", {})
    primary_token = str(accent.get("primary", "blue"))
    secondary_token = str(accent.get("secondary", "mauve"))
    primary_hex = colors.get(primary_token, "#89b4fa")
    secondary_hex = colors.get(secondary_token, "#cba6f7")

    return {
        "wallpaper": wallpaper,
        "palette_name": palette_name,
        "font_ui": font_ui,
        "font_mono": font_mono,
        "colors": colors,
        "primary_token": primary_token,
        "primary_hex": primary_hex,
        "secondary_hex": secondary_hex,
    }


def _write_palette_conf(tmp, ctx):
    lines = [f"# output_schema_version = {SCHEMA_VERSION}"]
    for name, hex_value in ctx["colors"].items():
        lines.append(f"${name} = rgba({hex_value.lstrip('#')}ff)")
    lines.append(f"$accent = rgba({ctx['primary_hex'].lstrip('#')}ff)")
    lines.append(f"$accent_secondary = rgba({ctx['secondary_hex'].lstrip('#')}ff)")
    (tmp / "palette.conf").write_text("\n".join(lines) + "\n")


def _write_palette_css(tmp, ctx):
    lines = [
        f"/* output_schema_version = {SCHEMA_VERSION} */",
        "/* Auto-generated by shedman theme apply; do not edit. */",
    ]
    for name, hex_value in ctx["colors"].items():
        lines.append(f"@define-color {name} {hex_value};")
    lines.append(f"@define-color accent {ctx['primary_hex']};")
    lines.append(f"@define-color accent_secondary {ctx['secondary_hex']};")
    (tmp / "palette.css").write_text("\n".join(lines) + "\n")


def _write_palette_lua(tmp, ctx):
    # Semantic keys only: hyprland.lua merges this over its Mocha
    # fallback, so every key here must stay in sync with SHEDOS_THEME.
    def rgba(hex_value, alpha):
        return f"rgba({hex_value.lstrip('#')}{alpha})"

    colors = ctx["colors"]
    lines = [
        f"-- output_schema_version = {SCHEMA_VERSION}",
        "-- Auto-generated by shedman theme apply; do not edit.",
        "-- Loaded by ~/.config/hypr/hyprland.lua into SHEDOS_THEME.",
        "return {",
        f'    active_border1  = "{rgba(ctx["primary_hex"], "ee")}",',
        f'    active_border2  = "{rgba(ctx["secondary_hex"], "ee")}",',
        f'    inactive_border = "{rgba(colors.get("surface2", "#585b70"), "aa")}",',
        f'    shadow          = "{rgba(colors.get("base", "#1e1e2e"), "ee")}",',
        "}",
    ]
    (tmp / "palette.lua").write_text("\n".join(lines) + "\n")


def _write_greeter_toml(tmp, ctx, target):
    doc = tomlkit.document()
    doc["output_schema_version"] = SCHEMA_VERSION
    # The desktop wallpaper daemon (awww) reads `wallpaper`; lock-screen
    # consumers (greeter, shedos-screensaver --mode=lock) read
    # `wallpaper_blurred` so the desktop stays sharp while the lock
    # surface is softened.
    doc["wallpaper"] = str(target / "wallpaper.png")
    doc["wallpaper_blurred"] = str(target / "wallpaper-blurred.png")
    fonts = tomlkit.table()
    fonts["ui"] = ctx["font_ui"]
    fonts["mono"] = ctx["font_mono"]
    doc["fonts"] = fonts
    colors = tomlkit.table()
    colors["base"] = ctx["colors"].get("base", "#1e1e2e")
    colors["text"] = ctx["colors"].get("text", "#cdd6f4")
    colors["accent"] = ctx["primary_hex"]
    colors["red"] = ctx["colors"].get("red", "#f38ba8")
    # Extended tokens for the shedos-power overlay (prompt-ui Theme
    # defaults cover them when an older render lacks these keys).
    colors["accent_secondary"] = ctx["secondary_hex"]
    colors["yellow"] = ctx["colors"].get("yellow", "#f9e2af")
    colors["mantle"] = ctx["colors"].get("mantle", "#181825")
    colors["surface0"] = ctx["colors"].get("surface0", "#313244")
    colors["surface2"] = ctx["colors"].get("surface2", "#585b70")
    colors["overlay1"] = ctx["colors"].get("overlay1", "#7f849c")
    doc["colors"] = colors
    (tmp / "greeter.toml").write_text(tomlkit.dumps(doc))


